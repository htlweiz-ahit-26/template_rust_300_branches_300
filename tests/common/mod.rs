use assert_cmd::Command;
use std::fs;
use walkdir::WalkDir;

#[macro_export]
macro_rules! io_test {
    ($test_name:ident) => {
        #[test]
        fn $test_name() {
            let test_name = stringify!($test_name);
            common::test_single_program(test_name);
        }
    };
}

macro_rules! str_line {
    () => {
        format!("{:-<70}", "-")
    };
}

macro_rules! error_check {
    ($test_name:expr, $stdin:expr, $should_be:expr, $is:expr) => {
        if $should_be != $is {
            let should_be_name = stringify!($should_be);
            let stdin = fs::read_to_string($stdin.clone()).unwrap_or_default();

            eprintln!(
                "{0}\nERROR: >>{should_be_name}<< missmatch in {1}\n{0}",
                str_line!(),
                $test_name
            );

            eprintln!(
                "This stdin was fed to the program:\n{0}\n{1}",
                str_line!(),
                stdin
            );
            eprintln!(
                "{0}\nThis >>{1}<< was expected!\n{0}\n{2}",
                str_line!(),
                should_be_name,
                $should_be,
            );
            eprintln!(
                "{0}\nBut this >>{1}<< was generated by the program!\n{0}\n{2}\n{0}",
                str_line!(),
                should_be_name,
                $is,
            );

            assert_eq!($should_be, $is);
        }
    };
}

pub fn test_single_program(test_name: &str) {
    eprintln!("Testing program: {}", test_name);

    let base_dir = format!("./tests/io_tests/{test_name}/");
    eprintln!("Testing {base_dir}");

    for test_directory in WalkDir::new(base_dir.clone()).max_depth(1).min_depth(1) {
        match test_directory {
            Ok(test_directory) => {
                let stdin = test_directory.path().join("stdin.txt");
                let stdout = test_directory.path().join("stdout.txt");
                let stderr = test_directory.path().join("stderr.txt");
                let stdout = fs::read_to_string(stdout).unwrap_or_default();
                let stderr = fs::read_to_string(stderr).unwrap_or_default();

                let mut cmd = Command::cargo_bin(test_name).expect("Cargo Error!");
                let cmd = cmd.pipe_stdin(stdin.clone()).unwrap();
                cmd.assert().success(); //.cmd.stdout(stdout).stderr(stderr);

                let result = cmd.unwrap();

                let out = String::from_utf8(result.stdout).unwrap();
                let err = String::from_utf8(result.stderr).unwrap();

                error_check!(test_name, stdin, stderr, err);
                error_check!(test_name, stdin, stdout, out);
            }
            Err(_) => println!("No test for {base_dir}!"),
        }
    }
}
